import { defineArrayMember, defineField, defineType } from "sanity"

export const homePage = defineType({
  name: "homePage",
  title: "Home Page",
  type: "document",
  groups: [
    { name: "hero", title: "Hero", default: true },
    { name: "features", title: "Featured content" },
    { name: "contact", title: "Contact" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({ name: "eyebrow", title: "Eyebrow", type: "string", group: "hero" }),
    defineField({
      name: "heading",
      title: "Main heading",
      type: "string",
      group: "hero",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "introduction",
      title: "Introduction",
      type: "text",
      rows: 4,
      group: "hero",
      validation: (rule) => rule.required().max(400),
    }),
    defineField({
      name: "featuredEvent",
      title: "Featured event",
      type: "reference",
      to: [{ type: "event" }],
      group: "features",
    }),
    defineField({
      name: "featuredAlbum",
      title: "Featured album",
      type: "reference",
      to: [{ type: "photoAlbum" }],
      group: "features",
    }),
    defineField({
      name: "nextChapterLabel",
      title: "Next chapter label",
      type: "string",
      group: "features",
      initialValue: "Chapter Two",
    }),
    defineField({
      name: "nextChapterTitle",
      title: "Next chapter title",
      type: "string",
      group: "features",
      initialValue: "TBD",
    }),
    defineField({
      name: "nextChapterCopy",
      title: "Next chapter message",
      type: "text",
      rows: 3,
      group: "features",
      initialValue: "The next chapter is still unwritten. Reach out to write yourself in.",
    }),
    defineField({
      name: "inquiryEmail",
      title: "Freaky Frank inquiry email",
      type: "email",
      group: "contact",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "artistBookingEmail",
      title: "Featured artist booking email",
      type: "email",
      group: "contact",
    }),
    defineField({
      name: "socialLinks",
      title: "Social links",
      type: "array",
      group: "contact",
      of: [defineArrayMember({ type: "link" })],
    }),
    defineField({ name: "seo", title: "SEO", type: "seo", group: "seo" }),
  ],
  preview: {
    select: { title: "heading", subtitle: "eyebrow" },
  },
})
